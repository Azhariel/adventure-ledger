-- Component tests for Session.lua (pure logic): time accounting, income, XP, rates, history, patterns.
return function(H)
    local S = H.load({ "Session.lua" }).Session

    H.test("elapsed time: zero duration at start, counts while running", function()
        local s = S.New(1000, 10, 0, 100)
        H.eq(S.Elapsed(s, 1000), 0, "boundary: zero duration")
        H.eq(S.Elapsed(s, 1090), 90)
    end)

    H.test("manual pause excludes paused time; pause/resume twice is harmless", function()
        local s = S.New(0)
        S.Pause(s, 100, "manual")
        S.Pause(s, 150, "manual")
        H.eq(S.Elapsed(s, 500), 100)
        S.Resume(s, 500)
        S.Resume(s, 510)
        H.eq(S.Elapsed(s, 560), 160)
    end)

    H.test("AFK pause: exactly 5 idle minutes before the flag are excluded (boundary)", function()
        local s = S.New(0)
        S.Touch(s, 600)
        S.Pause(s, 900, "afk") -- flagged 300s after the last activity
        H.eq(S.Elapsed(s, 2000), 600)
        H.eq(s.pauseReason, "afk")
    end)

    H.test("AFK pause: never excludes more than 5 minutes, nor active time before the last activity", function()
        local s = S.New(0)
        S.Touch(s, 100)
        S.Pause(s, 1000, "afk") -- idle 900s: only the last 300 are excluded
        H.eq(S.Elapsed(s, 1000), 700)
        local s2 = S.New(0)
        S.Touch(s2, 950)
        S.Pause(s2, 1000, "afk") -- /afk typed 50s after the last kill
        H.eq(S.Elapsed(s2, 1000), 950)
    end)

    H.test("AFK pause right after a resume excludes nothing before the resume", function()
        local s = S.New(0)
        S.Pause(s, 100, "manual")
        S.Resume(s, 1000)
        S.Pause(s, 1010, "afk")
        H.eq(S.Elapsed(s, 1010), 100)
    end)

    H.test("money: loot and quest kinds add up; zero, negative and unknown kinds are ignored", function()
        local s = S.New(0)
        S.AddMoney(s, 1, "loot", 150)
        S.AddMoney(s, 1, "quest", 50)
        S.AddMoney(s, 1, "loot", 0)
        S.AddMoney(s, 1, "loot", -20)
        S.AddMoney(s, 1, "vendor", 999)
        H.eq(s.money.loot, 150); H.eq(s.money.quest, 50)
        H.eq(S.Total(s), 200)
    end)

    H.test("item value decision table: AH after cut vs vendor, either missing", function()
        H.eq(S.ItemValue(100, 50), 95, "AH higher")
        H.eq(S.ItemValue(100, 96), 96, "vendor higher")
        H.eq(S.ItemValue(nil, 30), 30, "vendor only")
        H.eq(S.ItemValue(101, nil), 95, "AH only, cut floors to copper")
        H.eq(S.ItemValue(nil, 0), 0, "unsellable and unlisted")
    end)

    H.test("items: valued now, or pending until their data arrives, then credited to the zone they dropped in", function()
        local s = S.New(0)
        S.SetZone(s, 0, "Elwynn Forest")
        S.AddItem(s, 5, 2592, 3, 40, "[Wool Cloth]")
        S.AddItem(s, 6, 4306, 2, nil, "[Silk Cloth]")
        H.eq(s.itemValue, 120)
        H.eq(S.PendingItems(s)[1], 4306)
        S.SetZone(s, 10, "Westfall")
        H.truthy(S.Revalue(s, 4306, 100))
        H.eq(s.itemValue, 320)
        H.eq(s.zones["Elwynn Forest"].value, 320)
        H.eq(s.zones["Westfall"].value, 0)
        H.eq(S.Revalue(s, 4306, 100), false, "only once")
        H.eq(#S.PendingItems(s), 0)
    end)

    H.test("top items: sorted by value, limited", function()
        local s = S.New(0)
        for id = 1, 10 do
            S.AddItem(s, 0, id, 1, id * 10)
        end
        local top = S.TopItems(s, 8)
        H.eq(#top, 8)
        H.eq(top[1].itemID, 10); H.eq(top[8].itemID, 3)
    end)

    H.test("XP: plain gain, then a level-up counts the rest of the old level plus the new XP", function()
        local s = S.New(0, 10, 100, 1000)
        H.eq(S.XPUpdate(s, 1, 400, 1000, 10), 300)
        H.eq(S.XPUpdate(s, 2, 50, 1200, 11), 650, "600 left in level 10 + 50")
        H.eq(s.xp, 950)
        H.eq(s.level, 11)
    end)

    H.test("XP: new XP reported before the new level counts once (rollover by decrease)", function()
        local s = S.New(0, 10, 900, 1000)
        H.eq(S.XPUpdate(s, 1, 20, 1200, 10), 120)
        H.eq(S.XPUpdate(s, 1, 20, 1200, 11), 0, "the level change that follows adds nothing")
        H.eq(s.xp, 120)
    end)

    H.test("XP: unknown baseline or non-number input adds nothing", function()
        local s = S.New(0)
        H.eq(S.XPUpdate(s, 1, 500, 1000, 5), 0)
        H.eq(S.XPUpdate(s, 1, nil, 1000, 5), 0)
        H.eq(S.XPUpdate(s, 1, 600, 1000, 5), 100)
    end)

    H.test("rates: nil below one minute (boundary), per hour from there", function()
        H.eq(S.PerHour(100, 0), nil, "zero duration")
        H.eq(S.PerHour(100, 59), nil)
        H.eq(S.PerHour(100, 60), 6000)
        H.eq(S.PerHour(5000, 1800), 10000)
    end)

    H.test("time to level from the XP rate", function()
        local s = S.New(0, 10, 0, 1000)
        S.XPUpdate(s, 600, 500, 1000, 10) -- 500 XP in 10 min = 3000/h, 500 left
        H.near(S.TimeToLevel(s, 600), 600)
        local idle = S.New(0, 10, 0, 1000)
        H.eq(S.TimeToLevel(idle, 600), nil, "no XP coming in")
    end)

    H.test("zones: time only while running, gold per hour per zone, best first", function()
        local s = S.New(0)
        S.SetZone(s, 0, "A")
        S.AddMoney(s, 10, "loot", 100)
        S.SetZone(s, 600, "B")
        S.AddMoney(s, 700, "loot", 1000)
        S.Pause(s, 1200, "manual")
        local z = S.ZoneRates(s, 5000)
        H.eq(z[1].zone, "B"); H.eq(z[1].time, 600); H.eq(z[1].perHour, 6000)
        H.eq(z[2].zone, "A"); H.eq(z[2].time, 600); H.eq(z[2].perHour, 600)
    end)

    H.test("history keeps the newest 30 sessions and drops empty ones (boundary)", function()
        local h = {}
        for i = 1, 31 do
            S.PushHistory(h, { start = i, duration = 60 })
        end
        H.eq(#h, 30)
        H.eq(h[1].start, 31); H.eq(h[30].start, 2)
        S.PushHistory(h, { start = 99, duration = 0 })
        H.eq(h[1].start, 31, "zero-duration session not kept")
    end)

    H.test("summary records duration, income, XP and the top 3 zones", function()
        local s = S.New(0, 1, 0, 100)
        for i, zone in ipairs({ "A", "B", "C", "D" }) do
            S.SetZone(s, (i - 1) * 100, zone)
            S.AddMoney(s, (i - 1) * 100, "loot", i * 10)
        end
        local r = S.Summary(s, 400)
        H.eq(r.duration, 400); H.eq(r.loot, 100); H.eq(#r.zones, 3)
        H.eq(r.zones[1].zone, "D")
    end)

    H.test("format strings become patterns: the four enUS loot lines", function()
        local link = "|cffffffff|Hitem:2592::::::::|h[Wool Cloth]|h|r"
        local single = S.FormatToPattern("You receive loot: %s.")
        local multi = S.FormatToPattern("You receive loot: %sx%d.")
        local pushed = S.FormatToPattern("You receive item: %s.")
        local pushedMulti = S.FormatToPattern("You receive item: %sx%d.")
        local l, n = ("You receive loot: " .. link .. "x3."):match(multi)
        H.eq(l, link); H.eq(n, "3")
        H.eq(("You receive loot: " .. link .. "."):match(single), link)
        H.eq(("You receive item: " .. link .. "."):match(pushed), link)
        l, n = ("You receive item: " .. link .. "x12."):match(pushedMulti)
        H.eq(n, "12")
        H.eq(("You create: " .. link .. "."):match(single), nil, "crafting lines don't match")
    end)

    H.test("format strings: magic characters escaped, positional specifiers supported", function()
        local p = S.FormatToPattern("(%1$s) costs 100%% [%2$d]")
        local a, b = ("(x) costs 100% [7]"):match(p)
        H.eq(a, "x"); H.eq(b, "7")
        H.eq(S.FormatToPattern(nil), nil)
    end)
end
