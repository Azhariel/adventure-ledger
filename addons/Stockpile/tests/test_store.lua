-- Component tests for Store.lua (pure logic): equivalence partitions and boundary values.
return function(H)
    local function store()
        return H.load({ "Store.lua" }).Store
    end

    -- Two characters on Deadheart, one elsewhere.
    local function sample(S)
        local db = S.NewDB()
        local a = S.EnsureChar(db, "Azhariel", "Deadheart", "PRIEST")
        local b = S.EnsureChar(db, "Bankalt", "Deadheart", "MAGE")
        local c = S.EnsureChar(db, "Faraway", "Otherrealm", "MAGE")
        S.SetLocation(db, a, "bags", { [2592] = 20 })
        S.SetLocation(db, a, "bank", { [2592] = 10 })
        S.SetLocation(db, a, "mail", { [2592] = 4 })
        S.SetLocation(db, b, "bank", { [2592] = 50, [2589] = 3 })
        S.SetLocation(db, c, "bags", { [2592] = 99 })
        return db, a, b, c
    end

    H.test("Upgrade: invalid or old saved data is replaced, current data kept", function()
        local S = store()
        H.eq(S.Upgrade(nil).version, 1)
        H.eq(S.Upgrade({ version = 0, chars = {} }).version, 1)
        H.eq(next(S.Upgrade({ version = 1 }).chars), nil, "missing chars table")
        local db = { version = 1, chars = { x = {} } }
        H.eq(S.Upgrade(db), db)
    end)

    H.test("Add ignores nil, zero and negative counts (boundary 0/1)", function()
        local S, t = store(), {}
        S.Add(t, 1, 0); S.Add(t, 1, -3); S.Add(t, nil, 5); S.Add(t, 2, nil)
        H.eq(next(t), nil)
        S.Add(t, 1, 1); S.Add(t, 1, 2)
        H.eq(t[1], 3)
    end)

    H.test("SetLocation reports whether counts changed", function()
        local S = store()
        local db = S.NewDB()
        local key = S.EnsureChar(db, "A", "R", "PRIEST")
        H.eq(S.SetLocation(db, key, "bags", { [1] = 2 }), true)
        H.eq(S.SetLocation(db, key, "bags", { [1] = 2 }), false, "same counts")
        H.eq(S.SetLocation(db, key, "bags", { [1] = 2, [3] = 1 }), true, "item added")
        H.eq(S.SetLocation(db, key, "bags", { [1] = 2 }), true, "item removed")
        H.eq(S.SetLocation(db, "Nobody-R", "bags", {}), false, "unknown character")
    end)

    H.test("EnsureChar keeps counts when the character is seen again", function()
        local S = store()
        local db = S.NewDB()
        local key = S.EnsureChar(db, "A", "R", "PRIEST")
        S.SetLocation(db, key, "bags", { [1] = 2 })
        S.EnsureChar(db, "A", "R", "PRIEST")
        H.eq(db.chars[key].bags[1], 2)
        H.eq(key, "A-R")
    end)

    H.test("Count, character scope: only the current character, split by place", function()
        local S = store()
        local db, a = sample(S)
        local total, list = S.Count(db, 2592, "character", a)
        H.eq(total, 34)
        H.eq(#list, 1)
        H.eq(list[1].name, "Azhariel"); H.eq(list[1].realm, "Deadheart"); H.eq(list[1].class, "PRIEST")
        H.eq(list[1].bags, 20); H.eq(list[1].bank, 10); H.eq(list[1].mail, 4); H.eq(list[1].total, 34)
        H.eq(list[1].key, nil, "internal key not exposed")
    end)

    H.test("Count, realm scope: every character on the realm, other realms excluded", function()
        local S = store()
        local db, a = sample(S)
        local total, list = S.Count(db, 2592, "realm", a)
        H.eq(total, 84)
        H.eq(#list, 2)
        H.eq(list[1].name, "Azhariel", "current character first even with fewer")
        H.eq(list[2].name, "Bankalt")
    end)

    H.test("Count: characters with none are left out; nobody has it gives 0 and an empty list", function()
        local S = store()
        local db, a = sample(S)
        local total, list = S.Count(db, 2589, "realm", a)
        H.eq(total, 3); H.eq(#list, 1); H.eq(list[1].name, "Bankalt")
        total, list = S.Count(db, 12345, "realm", a)
        H.eq(total, 0); H.eq(#list, 0)
        total, list = S.Count(db, 2589, "character", a)
        H.eq(total, 0); H.eq(#list, 0)
    end)

    H.test("Count: unknown current character gives nothing", function()
        local S = store()
        local db = sample(S)
        H.eq(S.Count(db, 2592, "realm", "Ghost-Deadheart"), 0)
    end)

    H.test("OwnedMap sums places and characters; changing the copy leaves the store alone", function()
        local S = store()
        local db, a = sample(S)
        local own = S.OwnedMap(db, "character", a)
        H.eq(own[2592], 34); H.eq(own[2589], nil)
        local realm = S.OwnedMap(db, "realm", a)
        H.eq(realm[2592], 84); H.eq(realm[2589], 3)
        realm[2592] = 0
        own[2592] = nil
        H.eq(S.OwnedMap(db, "realm", a)[2592], 84)
        H.eq(db.chars[a].bags[2592], 20)
    end)

    H.test("Lines: header, then one line per character with only non-empty places", function()
        local S = store()
        local db, a = sample(S)
        local lines = S.Lines(S.Count(db, 2592, "realm", a))
        H.eq(lines[1], "Stockpile: 84")
        H.eq(lines[2], "  Azhariel: 20 bags, 10 bank, 4 mail")
        H.eq(lines[3], "  Bankalt: 50 bank")
        H.eq(#S.Lines(0, {}), 0, "total 0 shows nothing")
    end)

    H.test("ParseItemID accepts ids, numeric text and links; rejects the rest", function()
        local S = store()
        H.eq(S.ParseItemID(2592), 2592)
        H.eq(S.ParseItemID(" 2592 "), 2592)
        H.eq(S.ParseItemID("|cffffffff|Hitem:2592::::::::|h[Wool Cloth]|h|r"), 2592)
        H.eq(S.ParseItemID("wool"), nil)
        H.eq(S.ParseItemID(nil), nil)
    end)

    H.test("Forget removes a character once", function()
        local S = store()
        local db, _, b = sample(S)
        H.eq(S.Forget(db, b), true)
        H.eq(db.chars[b], nil)
        H.eq(S.Forget(db, b), false)
    end)
end
